export function getPropertyBySlug(slug: string, list: Property[] = properties) {
  return list.find((p) => p.slug === slug);
}

export function getFeaturedProperties(list: Property[] = properties) {
  const featured = list.filter((p) => p.featured).slice(0, 6);
  return featured.length ? featured : list.slice(0, 6);
}

export function countForLocation(match: string, list: Property[] = properties) {
  const q = match.toLowerCase();
  return list.filter((p) => {
    const blob = `${p.city} ${p.district} ${p.neighborhood}`.toLowerCase();
    return blob.includes(q);
  }).length;
}

export function statusLabel(status: ListingStatus) {
  if (status === "for-rent") return "For rent";
  if (status === "for-sale") return "For sale";
  return "Available";
}

export function typeLabel(type: PropertyKind) {
  const found = PROPERTY_TYPES.find((t) => t.value === type);
  return found?.label ?? type;
}
